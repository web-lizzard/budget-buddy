#!/usr/bin/env bash
# Host-only: read the Git identity that applies to this repo and write it to git.env
# so docker run --env-file can inject it. post-create then copies it into the container.
set -euo pipefail

INIT_D_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE_ROOT="$(cd "${INIT_D_DIR}/../.." && pwd)"
OUT="${INIT_D_DIR}/../git.env"

git_get() {
	git -C "${WORKSPACE_ROOT}" config --get "$1" 2>/dev/null || true
}

# Drop values that would break the single-line env-file format.
one_line() {
	local value="$1"
	value="${value//$'\r'/}"
	if [[ "${value}" == *$'\n'* ]]; then
		return 1
	fi
	printf '%s' "${value}"
}

name="$(git_get user.name)"
email="$(git_get user.email)"

if ! name="$(one_line "${name}")"; then
	echo "Host user.name contains a newline; not propagating it." >&2
	name=""
fi
if ! email="$(one_line "${email}")"; then
	echo "Host user.email contains a newline; not propagating it." >&2
	email=""
fi

{
	echo '# Generated by 06-sync-git-identity.sh — do not edit.'
	if [[ -n "${name}" ]]; then
		printf 'HOST_GIT_USER_NAME=%s\n' "${name}"
	fi
	if [[ -n "${email}" ]]; then
		printf 'HOST_GIT_USER_EMAIL=%s\n' "${email}"
	fi
} >"${OUT}"

if [[ -z "${name}" || -z "${email}" ]]; then
	echo "Host Git identity is incomplete (user.name='${name}', user.email='${email}')." >&2
	echo "Set both on the host (git config --global) and rebuild the container." >&2
else
	echo "Synced Git identity into ${OUT} (${name} <${email}>)"
fi
